import assert from 'node:assert';
process.env.TURSO_DATABASE_URL = 'file:' + process.env.TMP.split('\\').join('/') + '/lidtest.db';
process.env.TURSO_AUTH_TOKEN = '';
globalThis.fetch = async () => ({ ok: true, status: 200, json: async () => ({}), text: async () => '{}' });
const { initDb, getDb, setSystemSetting } = await import('../api/_lib/db.js');
await initDb();
const db = getDb();
await setSystemSetting('ai_enabled', '1');
await db.execute("DELETE FROM wa_lid_map"); await db.execute("DELETE FROM users WHERE id='tu1'");
await db.execute("INSERT INTO users (id,email,password_hash,name,phone) VALUES ('tu1','isa@x.com','x','Isa Teste','5561994408559')");
const { handleAssistantMessage } = await import('../api/_lib/assistant2.js');
const M = (t, extra = {}) => ({ key: { remoteJid: '999001@lid', fromMe: false, id: 'm' + Math.random(), ...extra }, message: { conversation: t } });
let r = await handleAssistantMessage(M('oi')); assert.equal(r.reason, 'lid_unknown', JSON.stringify(r));
r = await handleAssistantMessage(M('oi de novo')); assert.equal(r.reason, 'lid_unknown');
r = await handleAssistantMessage(M('meu email é isa@x.com')); assert.equal(r.reason, 'lid_code_sent');
let row = (await db.execute("SELECT * FROM wa_lid_map WHERE lid='999001'")).rows[0];
assert.ok(/^\d{6}$/.test(row.code)); assert.equal(row.pending_user_id, 'tu1');
r = await handleAssistantMessage(M(row.code === '000000' ? '111111' : '000000')); assert.equal(r.reason, 'lid_bad_code');
r = await handleAssistantMessage(M(row.code)); assert.equal(r.reason, 'lid_linked');
row = (await db.execute("SELECT * FROM wa_lid_map WHERE lid='999001'")).rows[0]; assert.equal(row.phone, '5561994408559');
r = await handleAssistantMessage({ key: { remoteJid: '999002@lid', fromMe: false }, message: { conversation: 'naoexiste@x.com' } }); assert.equal(r.reason, 'lid_code_sent');
assert.equal((await db.execute("SELECT pending_user_id FROM wa_lid_map WHERE lid='999002'")).rows.length, 0);
await handleAssistantMessage(M('oi', { remoteJid: '999003@lid', remoteJidAlt: '5561994408559@s.whatsapp.net' })).catch(() => {});
assert.equal((await db.execute("SELECT phone FROM wa_lid_map WHERE lid='999003'")).rows[0].phone, '5561994408559');
console.log('LID flow OK');
process.exit(0);
